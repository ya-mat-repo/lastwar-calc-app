/** トップページに出す候補（やる気が出る名言と、心が癒される名言を合わせたもの） */
export const QUOTES: readonly Quote[] = [...MOTIVATING_QUOTES, ...HEALING_QUOTES]

/** 名言を1つ選ぶ。random は 0 以上 1 未満の値を返す関数（テストで差し替えられるように引数にしている） */
export function pickQuote(random: () => number = Math.random): Quote {
  const index = Math.min(Math.floor(random() * QUOTES.length), QUOTES.length - 1)
  return QUOTES[index] ?? QUOTES[0]
}

